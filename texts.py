class _SD(dict):
    def __missing__(self, k):
        return "{" + k + "}"


async def t(key, **kw):
    raw = db.gs("t:" + key) or TEXTS[key][1]
    try:
        return raw.format_map(_SD(kw))
    except Exception:
        return raw


def btn_title(key):
    return db.gs("b:" + key) or BUTTONS[key][1]


def B(key, cb=None, url=None, title=None):
    """Кнопка с редактируемым названием и (опционально) премиум-эмодзи."""
    kw = {"text": title or btn_title(key)}
    if url:
        kw["url"] = url
    else:
        kw["callback_data"] = cb or key
    st = db.gs("s:" + key)
    if st in ("success", "primary", "danger"):
        kw["style"] = st  # цвет кнопки (Bot API 9.4)
    eid = db.gs("e:" + key)
    if eid:
        kw["icon_custom_emoji_id"] = eid  # extra-поле Bot API, aiogram пропускает
    return InlineKeyboardButton(**kw)


def esc(s):
    return html.escape(str(s or ""))


def money(x):
    return f"{float(x):.2f}".rstrip("0").rstrip(".") or "0"
